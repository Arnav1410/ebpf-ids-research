#!/usr/bin/env python3
"""Select scales using calibration rows ONLY, then measure held-out fidelity."""
import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import struct
import sys

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from validation.reference import Model, STAGES, read_npy_rows
from quantization.reference import ExactModel, LayerModel, ArithmeticFailure, round_div

SEED = b'lsfp-20261107\0'


def split(rows):
    calibration, evaluation = [], []
    for i, row in enumerate(rows):
        digest = hashlib.sha256(SEED+struct.pack('<6q', *row)).digest()
        (calibration if int.from_bytes(digest[:8], 'big') < (1 << 62) else evaluation).append(i)
    return calibration, evaluation


def select(source, calibration_rows):
    bounds = []
    for j in range(6):
        delta = max(abs(row[j]-source.mean[j]) for row in calibration_rows)
        b = 1
        while b*source.scale[j] < 2*delta: b *= 2
        bounds.append(b)
    qn = max(q for q in range(25) if max(bounds)*(1 << q) < (1 << 30))
    integer_bounds = [b << qn for b in bounds]
    bound_history, accumulator_bounds, outputs = [integer_bounds], [], []
    qx = qn
    for weights, rows in zip(source.weights, (32, 32, 2)):
        n = len(integer_bounds)
        accumulators = [sum(abs(weights[i*n+j])*integer_bounds[j] for j in range(n)) for i in range(rows)]
        if max(accumulators) > (1 << 63)-1: raise ValueError('Conservative int64 bound failed')
        allowed = [q for q in range(31) if 0 <= qx+16-q <= 62 and
                   max((a+(1 << (qx+16-q))-1) >> (qx+16-q) for a in accumulators) < (1 << 30)]
        if not allowed: raise ValueError('No safe output exponent')
        qz = max(allowed); bits = qx+16-qz
        integer_bounds = [(a+(1 << bits)-1) >> bits for a in accumulators]
        outputs.append(qz); accumulator_bounds.append(max(accumulators)); bound_history.append(integer_bounds)
        qx = qz
    parameter_candidates = []
    for i, weights in enumerate(source.weights):
        parameter_candidates.append([dict(q=q,
            max_abs_error=max(abs(round_div(w, 1 << (16-q))/(1 << q)-w/65536) for w in weights),
            mean_abs_error=sum(abs(round_div(w, 1 << (16-q))/(1 << q)-w/65536) for w in weights)/len(weights))
            for q in range(12, 17)])
    return dict(schema=1, q_normalized=qn, q_weights=[16]*3, q_outputs=outputs,
                normalized_domain=bounds, delta_limits=[b*s for b, s in zip(bounds, source.scale)],
                accumulator_abs_bounds=accumulator_bounds, integer_abs_bounds=bound_history,
                weight_candidates=parameter_candidates, rounding='nearest_even', overflow='reject_prediction',
                biases='absent: exact zero at each accumulator exponent',
                source_header_sha256=hashlib.sha256((ROOT/'src/mlp_params.bpf.h').read_bytes()).hexdigest())


def emit_header(model):
    c = model.config
    return ('/* Generated by quantization/calibrate.py from the unchanged Q16 header. */\n'
            '#ifndef LS_CALIBRATED_H\n#define LS_CALIBRATED_H\n'
            '#include "arithmetic.h"\n'
            f'#define LS_PARAMETER_SHA256 "{c["parameter_sha256"]}"\n'
            'static const struct ls_metadata ls_calibrated_metadata = {\n'
            f'    .magic=0x4c535031, .version=1, .q_normalized={c["q_normalized"]},\n'
            '    .q_weight={'+','.join(map(str, c['q_weights']))+'},\n'
            '    .q_output={'+','.join(map(str, c['q_outputs']))+'},\n'
            '    .reserved=0, .delta_limit={'+','.join(str(v)+'ULL' for v in c['delta_limits'])+'}\n};\n'
            '#endif\n')


def evaluate(source, experimental, rows, indices):
    exact = ExactModel(source)
    errors = {mode: {stage: dict(max_abs=0., sum_abs=0., values=0) for stage in STAGES}
              for mode in ('static_q16', 'layer_specific')}
    agreement = Counter(); failures = Counter(); samples = []; flips = []
    for index in indices:
        raw = rows[index]
        exact_values, denominators, exact_label = exact.infer(raw)
        static_events = []
        static_values, static_label = source.infer(raw, static_events)
        failures.update('static:'+event['kind'] for event in static_events)
        try: exp_values, exp_label = experimental.infer(raw)
        except ArithmeticFailure as error:
            failures['experimental:'+error.code] += 1
            continue
        agreement['compared'] += 1
        agreement['modes_agree'] += static_label == exp_label
        agreement['static_reference_agree'] += static_label == exact_label
        agreement['experimental_reference_agree'] += exp_label == exact_label
        if static_label != exp_label:
            agreement['prediction_flips'] += 1
            if len(flips) < 8: flips.append(dict(index=index, raw=raw, static=static_label, experimental=exp_label, reference=exact_label))
        for mode, values, exponents in (('static_q16', static_values, [16]*6),
                                        ('layer_specific', exp_values, experimental.exponents)):
            for stage, q in zip(STAGES, exponents):
                denominator = denominators[stage]
                for actual, reference in zip(values[stage], exact_values[stage]):
                    error = abs(actual*denominator-reference*(1 << q))/(denominator*(1 << q))
                    e = errors[mode][stage]; e['max_abs'] = max(e['max_abs'], error)
                    e['sum_abs'] += error; e['values'] += 1
        if len(samples) < 3:
            samples.append(dict(index=index, raw=raw, static_q16=static_values, layer_specific=exp_values,
                experimental_exponents=experimental.exponents,
                exact_logit_numerators=exact_values['logits'],exact_logit_denominator=denominators['logits'],
                labels=dict(static=static_label, experimental=exp_label, reference=exact_label)))
    for metrics in errors.values():
        for e in metrics.values():
            e['mean_abs'] = e.pop('sum_abs')/e['values'] if e['values'] else None
    return dict(reference='Exact rational network reconstructed from Q16 weights and rounded header scaler; not original FP32',
                held_out_rows=len(indices), agreement=dict(agreement), arithmetic_events=dict(failures),
                saturation_events=0, errors=errors, representative_samples=samples, flip_examples=flips)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args(); args.output.mkdir(parents=True, exist_ok=False)
    source = Model.load(ROOT/'src/mlp_params.bpf.h')
    rows = read_npy_rows(ROOT/'dataset/reproduction-xdp-data.npy')
    cal, heldout = split(rows)
    config = select(source, [rows[i] for i in cal])
    assert config == select(source, [rows[i] for i in cal]), 'Selection must be deterministic'
    config.update(seed=SEED.decode().rstrip('\0'), split='SHA256 feature-group, unsigned first64 < 2**62',
                  calibration_rows=len(cal), held_out_rows=len(heldout),
                  data_sha256=hashlib.sha256((ROOT/'dataset/reproduction-xdp-data.npy').read_bytes()).hexdigest())
    model = LayerModel(source, config); config['parameter_sha256'] = hashlib.sha256(model.packed()).hexdigest()
    # Freeze the generated configuration BEFORE accessing held-out predictions.
    (ROOT/'quantization/calibrated.json').write_text(json.dumps(config, indent=2)+'\n')
    (ROOT/'quantization/calibrated.h').write_text(emit_header(model))
    (args.output/'scale_config.json').write_text(json.dumps(config, indent=2)+'\n')
    calibration_max = {stage: 0. for stage in STAGES}
    exact = ExactModel(source)
    for i in cal:
        values, denominators, _ = exact.infer(rows[i])
        for stage in STAGES: calibration_max[stage] = max(calibration_max[stage], max(abs(v)/denominators[stage] for v in values[stage]))
    (args.output/'calibration_ranges.json').write_text(json.dumps(calibration_max, indent=2)+'\n')
    metrics = evaluate(source, model, rows, heldout)
    (args.output/'numerical_metrics.json').write_text(json.dumps(metrics, indent=2)+'\n')
    summary = dict(q_normalized=config['q_normalized'], q_weights=config['q_weights'], q_outputs=config['q_outputs'],
                   calibration_rows=len(cal), held_out_rows=len(heldout), agreement=metrics['agreement'],
                   arithmetic_events=metrics['arithmetic_events'], errors=metrics['errors'])
    print(json.dumps(summary, indent=2), flush=True)


if __name__ == '__main__': main()
